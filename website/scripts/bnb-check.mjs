import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import Papa from "papaparse";

const wards = JSON.parse(readFileSync(new URL("../src/features/bnb/wards.json", import.meta.url), "utf8")).features;
const ward = name => wards.find(w => w.properties.name === name);
export async function checkBnb({ context, origin, evidence, basePath = "/map-master" }) {
  const page = await context.newPage(), errors = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
  await page.route("https://tiles.openfreemap.org/**", route => route.fulfill({ json: { version: 8, sources: {}, layers: [{ id: "background", type: "background", paint: { "background-color": "#eef0e8" } }] } }));
  const ready = async () => { await page.locator('[data-bnb][data-ready="true"]').waitFor(); await idle(); };
  const idle = () => page.locator('.bb-map-canvas[aria-busy="false"]').waitFor();
  const count = value => page.locator(`[data-bnb][data-location-count="${value}"]`).waitFor();
  const stat = name => page.locator(`[data-bnb-stat="${name}"]`).textContent();
  const choose = async name => { await page.getByLabel("Zoek een wijk", { exact: true }).fill(name); await page.getByRole("button", { name: `Selecteer ${name}`, exact: true }).click(); await idle(); };
  const camera = async () => JSON.parse(await page.locator(".bb-map-canvas").getAttribute("data-camera"));
  const sameCamera = async before => { await idle(); assert.deepEqual(await camera(), before, "Area selection preserves position and zoom"); };
  const pointOnMap = async coordinates => {
    const [lng, lat, zoom] = await camera(), bounds = await page.locator(".bb-map-canvas").boundingBox();
    const mercator = (lng, lat) => [(lng + 180) / 360, (1 - Math.log(Math.tan(Math.PI / 4 + lat * Math.PI / 360)) / Math.PI) / 2];
    const c = mercator(lng, lat), p = mercator(...coordinates), world = 512 * 2 ** zoom;
    return { x: bounds.x + bounds.width / 2 + (p[0] - c[0]) * world, y: bounds.y + bounds.height / 2 + (p[1] - c[1]) * world };
  };
  const hover = async name => { await idle(); const p = await pointOnMap(ward(name).properties.anchor); await page.mouse.move(p.x, p.y); await page.locator('.bb-hover-card:not([hidden])').waitFor(); return p; };
  const card = page.locator(".bb-hover-card");
  const exportData = async name => { await page.getByLabel("Exporteer B&B-voorbeeld", { exact: true }).click(); const pending = page.waitForEvent("download"); await page.getByRole("button", { name, exact: true }).click(); return readFileSync(await (await pending).path(), "utf8"); };
  try {
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(`${origin}${basePath}/analysis/bnb/`); await ready(); await count(0);
    assert.equal(await page.locator(".docs-shell").count(), 0);
    assert.equal(await stat("free"), "1.726"); assert.equal(await stat("granted"), "2.975"); assert.equal(await stat("pending"), "651");
    assert.equal(await page.locator(".bb-ward").count(), 110);
    assert.equal(await page.getByLabel("Informatie bij aanwijzen", { exact: true }).inputValue(), "follow");
    await page.screenshot({ path: resolve(evidence, "bnb-wards-overview.png") });
    assert.match(await stat("median-pending"), /dagen/);
    await page.getByLabel("Vergelijk vergunningruimte", {exact:true}).selectOption("share");
    assert.match(await page.locator(".bb-comparison button").first().textContent(), /%/);
    await page.getByLabel("Vergelijk vergunningruimte", {exact:true}).selectOption("count");
    const overviewCamera = await camera();
    const point = await hover("Waterland");
    assert.match(await card.textContent(), /Waterland/);
    assert.match(await card.textContent(), /Aanvragen in behandeling/);
    const firstBox = await card.boundingBox();
    await page.mouse.move(point.x + 3, point.y + 2);
    const movedBox = await card.boundingBox();
    assert.ok(Math.abs(movedBox.x - firstBox.x) > 1 || Math.abs(movedBox.y - firstBox.y) > 1, "Properties follow pointer movement");
    const mapBox = await page.locator(".bb-map-canvas").boundingBox();
    assert.ok(movedBox.x >= mapBox.x && movedBox.y >= mapBox.y && movedBox.x + movedBox.width <= mapBox.x + mapBox.width && movedBox.y + movedBox.height <= mapBox.y + mapBox.height);
    assert.equal(await page.evaluate(p => document.elementFromPoint(p.x, p.y).tagName, point), "CANVAS", "Following information cannot intercept map clicks");
    await page.screenshot({ path: resolve(evidence, "bnb-follow-properties.png") });
    const infoMode = page.getByLabel("Informatie bij aanwijzen", { exact: true });
    await infoMode.selectOption("fixed"); await hover("Waterland");
    const fixed = await card.boundingBox();
    assert.ok(Math.abs(fixed.x+fixed.width/2-mapBox.x-mapBox.width/2)<2 && Math.abs(fixed.y+fixed.height/2-mapBox.y-mapBox.height/2)<2,"Fixed properties are centered on the map"); await page.mouse.move(point.x + 3, point.y + 2);
    const stillFixed = await card.boundingBox(); assert.equal(stillFixed.x, fixed.x); assert.equal(stillFixed.y, fixed.y);
    await infoMode.selectOption("click"); await page.mouse.move(point.x,point.y); assert.equal(await card.isVisible(),false,"Click-only mode suppresses hover");
    await page.mouse.click(point.x,point.y); await page.locator('.bb-hover-card[data-pinned="true"]').waitFor();await sameCamera(overviewCamera);
    await page.mouse.move(20,20);assert.equal(await card.isVisible(),true,"Clicked properties stay open after leaving the object");
    await page.getByRole('button',{name:'Sluit eigenschappen',exact:true}).click();assert.equal(await card.isVisible(),false);
    await infoMode.selectOption("off"); await page.mouse.move(point.x, point.y);
    assert.equal(await card.isVisible(), false);
    await infoMode.selectOption("follow"); await hover("Jordaan");
    await page.locator(".bb-map-canvas canvas").focus(); await page.keyboard.press("Escape");
    assert.equal(await card.isVisible(), false);

    // Select an actual polygon on the canvas; selection must leave the camera untouched.
    const target = await pointOnMap(ward("Jordaan").properties.anchor);
    await page.mouse.click(target.x, target.y); await count(12); await sameCamera(overviewCamera);
    assert.equal(await page.locator("[data-bnb]").getAttribute("data-selected"), ward("Jordaan").properties.code);
    assert.equal(await stat("free"), "25"); assert.equal(await stat("pending"), "8");
    await page.getByRole("button", { name: "Zoom naar selectie", exact: true }).click(); await idle();
    assert.notDeepEqual(await camera(), overviewCamera, "Explicit zoom still frames a chosen ward");
    await page.getByLabel("Status vergunning", { exact: true }).selectOption("pending"); await count(8); await idle();
    assert.equal(await stat("granted"), "4", "Location filtering must not alter quota statistics");
    const exported = JSON.parse(await exportData("Locaties GeoJSON"));
    assert.equal(exported.features.length, 8); assert.ok(exported.features.every(f => f.properties.status === "pending" && f.properties.dataType === "fictief"));
    const firstId = exported.features[0].id;
    const beforePermit = await camera();
    await page.getByRole("button", { name: `Toon ${firstId} op kaart`, exact: true }).click(); await page.locator(".bb-popup").waitFor(); await idle();
    assert.match(await page.locator(".bb-popup").textContent(), new RegExp(firstId));
    await sameCamera(beforePermit);
    await page.getByRole("button", { name: "Deselecteer locatie", exact: true }).click(); await idle();
    const permitPoint = await pointOnMap(exported.features[0].geometry.coordinates);
    await page.mouse.click(permitPoint.x, permitPoint.y); await page.locator(".bb-popup").waitFor();
    assert.match(await page.locator(".bb-popup").textContent(), new RegExp(firstId));
    await page.getByLabel("Zoek vergunninglocaties", { exact: true }).fill("geen-match"); await count(0);
    await page.getByRole("button", { name: "Wis de locatiefilters", exact: true }).click(); await count(12);
    const beforeBellamy = await camera(); await choose("Bellamybuurt"); await count(56); await sameCamera(beforeBellamy);
    assert.equal(await stat("free"), "4");
    await page.getByRole("button", { name: "Zoom naar selectie", exact: true }).click(); await idle();
    const forecast = page.getByLabel("Toon deze situatie op de kaart", { exact: true });
    await forecast.check(); assert.equal(await stat("free"), "0");
    await forecast.uncheck(); assert.equal(await stat("free"), "4");
    const csv = Papa.parse(await exportData("Locaties CSV"), { header: true });
    assert.equal(csv.data.length, 56); assert.ok(csv.data.every(row => row.wijk_id === ward("Bellamybuurt").properties.code));
    await forecast.check(); await page.getByRole("button", { name: /Heel Amsterdam/ }).click(); await count(0);
    assert.equal(await stat("free"), "1.244"); assert.equal(Papa.parse(await exportData("Wijken CSV"), { header: true }).data.length, 110);
    await choose("Havens-West"); await page.getByLabel("Status vergunning", { exact: true }).selectOption("pending"); await count(0);
    assert.equal(await stat("pending"), "0");
    const help = page.getByRole("button", { name: "Uitleg B&B-voorbeeld", exact: true }); await help.click();
    const dialog = page.getByRole("dialog", { name: "Zo werkt het B&B-voorbeeld", exact: true }); await dialog.waitFor();
    assert.match(await dialog.textContent(), /110 wijkpolygonen/); assert.match(await dialog.textContent(), /Info volgt muis/);
    await page.keyboard.press("Escape"); await dialog.waitFor({ state: "detached" });
    assert.equal(await help.evaluate(node => node === document.activeElement), true);
    await page.setViewportSize({ width: 360, height: 800 });
    await page.getByRole("button", { name: "Wijken", exact: true }).click(); await choose("Jordaan"); await count(12);
    await page.getByRole("button", { name: "Zoom naar selectie", exact: true }).click(); await idle();
    await page.getByRole("button", { name: "Inzichten", exact: true }).click();
    assert.equal(await page.locator('[data-bnb-stat="pending"]').isVisible(), true);
    await page.getByRole("button", { name: "Sluit inzichten", exact: true }).click(); await idle();
    await page.screenshot({ path: resolve(evidence, "bnb-wards-mobile.png") });
    for (const width of [360, 800, 1000, 1001, 1440]) {
      await page.setViewportSize({ width, height: 850 });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    }
    await page.evaluate(() => { localStorage.setItem("map-master-analysis-intro-v1", "seen"); window.__bnbOldGL = document.querySelector(".bb-map-canvas canvas").getContext("webgl2"); });
    await page.getByRole("link", { name: "Vrije analyse", exact: true }).click(); await page.locator('[data-analysis][data-ready="true"]').waitFor();
    await page.waitForFunction(() => window.__bnbOldGL.isContextLost());
    await page.getByRole("link", { name: /B&B permit dashboard/ }).click(); await ready();
    assert.deepEqual(errors, []);
    console.log("✓ B&B: 110 source wards, follow/fixed/off properties, edge containment, polygon/marker clicks, camera preservation, independent quota filters, exports, search, mobile and cleanup");
  } finally { await page.close(); }
}
