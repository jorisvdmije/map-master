import { Map, setWorkerUrl, type GeoJSONSource } from 'maplibre-gl';
import workerUrl from 'maplibre-gl/dist/maplibre-gl-worker.mjs?url';
import { afterEach, expect, it, vi } from 'vitest';
import { GeometryEditor, type GeometryFeatureCollection, type Coordinate, type FeatureId } from '../../src/index.js';
import 'maplibre-gl/dist/maplibre-gl.css';
setWorkerUrl(workerUrl);
let map: Map | undefined, editor: GeometryEditor | undefined, container: HTMLDivElement | undefined;
afterEach(() => { vi.restoreAllMocks(); editor?.destroy(); map?.remove(); container?.remove(); });
it('applies native worker diffs, preserves typed selection and serializes below the size threshold', async () => {
  container = document.createElement('div'); container.style.cssText = 'width:700px;height:450px;'; document.body.append(container);
  map = new Map({ container, center: [4.9, 52.37], zoom: 13, fadeDuration: 0, style: { version: 8, sources: {}, layers: [] } });
  await new Promise<void>(resolve => { map!.once('load', () => { resolve(); }); });
  editor = new GeometryEditor(map);
  const features: GeometryFeatureCollection['features'] = Array.from({ length: 1001 }, (_, index) => ({ type: 'Feature', id: index === 1 ? '0' : index, properties: { name: `Point ${index}` }, geometry: { type: 'Point', coordinates: [4.9 + index * .000001, 52.37] } }));
  editor.importGeoJSON({ type: 'FeatureCollection', features }); editor.clearHistory(); editor.select(0);
  const id = Object.keys(map.getStyle().sources).find(id => id.endsWith('-features'))!;
  const source = map.getSource<GeoJSONSource>(id)!;
  const position = async (id: FeatureId): Promise<Coordinate | null> => {
    const data = await source.getData();
    if (data.type !== 'FeatureCollection') return null;
    const point = data.features.find(feature => feature.id === id)?.geometry;
    return point?.type === 'Point' ? point.coordinates as Coordinate : null;
  };
  await expect.poll(() => position(0)).toEqual([4.9, 52.37]);
  const full = vi.spyOn(source, 'setData'), incremental = vi.spyOn(source, 'updateData');
  editor.applyTransaction({ update: [{ ...features[0]!, geometry: { type: 'Point', coordinates: [4.91, 52.38] } }] });
  await expect.poll(() => position(0)).toEqual([4.91, 52.38]);
  expect(full).not.toHaveBeenCalled(); expect(incremental).toHaveBeenCalledOnce();
  expect(incremental.mock.calls[0]![0].add).toHaveLength(1);
  expect(await position('0')).toEqual([4.9 + .000001, 52.37]);
  expect(editor.getState().selectedFeatureId).toBe(0);
  expect((map.getFeatureState({ source: id, id: JSON.stringify(0) }) as Record<string, unknown>).selected).toBe(true);
  editor.undo(); await expect.poll(() => position(0)).toEqual([4.9, 52.37]);
  editor.redo(); await expect.poll(() => position(0)).toEqual([4.91, 52.38]);
  editor.applyTransaction({ delete: features.slice(2).map(feature => feature.id) });
  editor.applyTransaction({ update: [{ ...features[0]!, geometry: { type: 'Point', coordinates: [4.92, 52.39] } }] });
  await expect.poll(() => position(0)).toEqual([4.92, 52.39]);
  const result = await source.getData(); expect(result.type === 'FeatureCollection' ? result.features.length : -1).toBe(2);
  expect(full).not.toHaveBeenCalled();
});
