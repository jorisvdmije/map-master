import { Map, setWorkerUrl, type GeoJSONSource, type StyleSpecification } from 'maplibre-gl';
import workerUrl from 'maplibre-gl/dist/maplibre-gl-worker.mjs?url';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { page, userEvent } from 'vitest/browser';
import { GeometryEditor, type Coordinate } from '../../src/index.js';
import 'maplibre-gl/dist/maplibre-gl.css';
setWorkerUrl(workerUrl);
let container: HTMLDivElement; let map: Map; let editor: GeometryEditor;
const style = (): StyleSpecification => ({ version: 8, sources: {}, layers: [{ id: 'background', type: 'background', paint: {'background-color':'#f8fafc'} }] });
const sourceId = (suffix: string) => Object.keys(map.getStyle().sources).find(id => id.endsWith(suffix))!;
const data = async () => JSON.stringify(await map.getSource<GeoJSONSource>(sourceId('-draft'))!.getData());
const ring: Coordinate[] = [[0,0],[10,0],[10,10],[0,10],[0,0]];
const cut: Coordinate[] = [[-1,3],[11,3]];
beforeEach(async () => {
  container = document.createElement('div'); container.style.cssText = 'width:700px;height:450px;position:relative;'; document.body.append(container);
  map = new Map({ container, center: [5,5], zoom: 4, style: style(), fadeDuration: 0 });
  await new Promise<void>(resolve => { map.once('load', () => { resolve(); }); });
  editor = new GeometryEditor(map);
  editor.importGeoJSON({type:'Feature',id:'target',properties:null,geometry:{type:'Polygon',coordinates:[ring]}});
  editor.select('target'); editor.clearHistory();
});
afterEach(() => { vi.restoreAllMocks(); editor.destroy(); map.remove(); container.remove(); });
it.each(['split','reshape'] as const)('renders %s contacts, localized errors and original comparison without committed uploads', async kind => {
  const before = editor.exportGeoJSON();
  const uploads = vi.spyOn(map.getSource<GeoJSONSource>(sourceId('-features'))!, 'setData');
  const set = (path: Coordinate[]) => kind === 'split' ? editor.setSplitLine(path) : editor.setReshapePath(path);
  if (kind === 'split') editor.splitSelected(); else editor.reshapeSelected();
  set([[0,3],[5,3]]);
  await expect.poll(data).toContain('cut-problem');
  const errorLayer = map.getStyle().layers.find(layer => layer.id.endsWith('-cut-problems'))!.id;
  await expect.poll(() => map.queryRenderedFeatures(map.project([5,3]), {layers:[errorLayer]}).length).toBeGreaterThan(0);
  expect(editor.getState().canFinish).toBe(false);
  set(kind === 'split' ? cut : [[0,3],[5,2],[10,3]]);
  await expect.poll(data).not.toContain('cut-problem');
  await expect.poll(data).toContain('cut-contact');
  expect(editor.getCutFeedback()!.contacts).toHaveLength(2);
  expect(map.getFeatureState({source:sourceId('-features'),id:'"target"'})).toMatchObject({comparison:true,editing:true});
  const feedback = editor.getCutFeedback();
  await userEvent.hover(map.getCanvas(), {position:{x:350,y:100}});
  expect(editor.getCutFeedback()).toEqual(feedback); expect(editor.exportGeoJSON()).toEqual(before); expect(uploads).not.toHaveBeenCalled();
  set([[0,3],[5,3]]); await expect.poll(data).toContain('cut-problem');
  expect(map.getFeatureState({source:sourceId('-features'),id:'"target"'})).not.toMatchObject({comparison:true});
  await userEvent.click(map.getCanvas(),{position:{x:350,y:350}}); await userEvent.keyboard('{Escape}');
  expect(editor.getCutFeedback()).toBeNull(); await expect.poll(data).not.toContain('cut-');
  expect(editor.exportGeoJSON()).toEqual(before); expect(editor.getState().canUndo).toBe(false);
});
it('restores feedback after a camera/style change and removes it on Apply and Undo', async () => {
  const before = editor.exportGeoJSON(); editor.splitSelected(); editor.setSplitLine(cut);
  await expect.poll(data).toContain('cut-contact');
  map.jumpTo({bearing:25,pitch:35});
  const loaded = new Promise<void>(resolve => { map.once('style.load', () => { resolve(); }); });
  map.setStyle(style(), {diff:false}); await loaded;
  await expect.poll(data).toContain('cut-contact');
  const contactLayer = map.getStyle().layers.find(layer => layer.id.endsWith('-cut-contacts'))!.id;
  await expect.poll(() => map.queryRenderedFeatures(map.project([0,3]), {layers:[contactLayer]}).length).toBeGreaterThan(0);
  expect(map.getFeatureState({source:sourceId('-features'),id:'"target"'})).toMatchObject({comparison:true});
  editor.finishSplit(); expect(editor.getCutFeedback()).toBeNull(); await expect.poll(data).not.toContain('cut-');
  editor.undo(); expect(editor.exportGeoJSON()).toEqual(before); expect(editor.getState().canUndo).toBe(false);
});
it.each(['lock','destroy'] as const)('clears feedback when the active operation ends through %s', async action => {
  editor.reshapeSelected(); editor.setReshapePath([[0,3],[5,3]]);
  await expect.poll(data).toContain('cut-problem');
  if (action === 'lock') editor.setLockedFeatureIds(['target']); else editor.destroy();
  expect(editor.getCutFeedback()).toBeNull(); expect(editor.getState().canUndo).toBe(false);
  if (action === 'lock') await expect.poll(data).not.toContain('cut-');
  else expect(Object.keys(map.getStyle().sources)).toEqual([]);
});
it('shows the crossing and both implicated segments for a self-intersecting route', async () => {
  editor.splitSelected(); editor.setSplitLine([[0,2],[8,8],[2,8],[10,2]]);
  await expect.poll(data).toContain('cut-problem');
  expect(editor.getCutFeedback()!.problemPoints).toEqual([[5,5.75]]);
  const lineLayer = map.getStyle().layers.find(layer => layer.id.endsWith('-cut-problem-lines'))!.id;
  await expect.poll(() => map.queryRenderedFeatures(map.project([4,5]), {layers:[lineLayer]}).length).toBeGreaterThan(0);
  await page.screenshot({path:'artifacts/cut-feedback-invalid.png'});
  editor.setSplitLine(cut); await expect.poll(data).not.toContain('cut-problem');
  await page.screenshot({path:'artifacts/cut-feedback-valid.png'});
});
